#!/usr/bin/env python3
"""Transcode the committed studio ident into the file the game plays.

    python3 tools/art/build_ui_video.py            # encode + verify + manifest
    python3 tools/art/build_ui_video.py --check    # verify only, write nothing

Why this file exists: ``branding_studio_present.mp4`` at the repository root
(768x768, 24 fps, 10.1 s, with an audio bed) is the *studio's* brand film -- a
company ident, the beat a Garena or Moonton title opens on. It was not made
here, it is not this project's artwork, and the only thing this tool does is
put it in a container Godot can decode: 4.7.2 ships ``modules/theora``, whose
``ResourceFormatLoaderTheora`` claims ``.ogv`` on every platform it builds for,
web included. Theora + Vorbis is therefore the target, and nothing else.

What it produces:

  * ``studio_ident.ogv`` -- the committed mp4, re-encoded, nothing added and
    nothing cut: the same 24 fps, the same square frame, the same audio. It is
    *not* cropped to 16:9, not letterboxed into 1280x720, not re-timed and not
    re-scored. The stage fits the square into whatever screen it is given
    (see ``StageStudioIdent._layout_video``), which is the only place that knows
    the screen; baking a 16:9 frame here would crop the ident's own margins on
    every device whose aspect that frame was not authored for.

Rules it keeps:

  * the single input is the file the project committed, at the path named by
    ``SOURCE``; a missing source is an error, never a placeholder;
  * the encode is deterministic: same input and same settings -> same file;
  * frames are sampled back *out of the encoded file* and audited against the
    ART_DIRECTION palette with the same ``audit()`` the textures use, so the
    audit covers what ships rather than what was intended;
  * if no encoder can be found the tool says so and exits non-zero. It never
    writes an empty file and never claims a video exists.

Requires Pillow and an ffmpeg with libtheora. Point ``FFMPEG`` at one, put one
on ``PATH``, or ``pip3 install --break-system-packages imageio-ffmpeg``.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

try:
    from PIL import Image
except ImportError:  # pragma: no cover
    print("ERROR: Pillow is not installed (pip3 install --break-system-packages Pillow)")
    raise SystemExit(2)

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_ui_art as art  # noqa: E402  (the palette audit lives there)

OUT = art.OUT
MANIFEST = OUT / "video_manifest.json"

# What the video is, in one line, written into the manifest beside its numbers.
ROLE = (
    "studio ident: shown once at launch, before the game's own logo, with no "
    "product UI on it, never replayed from a menu and never stood in for"
)

# The committed ident, as delivered. Never regenerated by this tool.
SOURCE = ROOT / "branding_studio_present.mp4"
IDENT_OUT = "studio_ident.ogv"
# The source's own frame rate is 24 and re-encoding at a different one would
# duplicate or drop frames for no gain; recorded here so --check has something
# to compare against if the source is ever replaced.
IDENT_FPS = 24

THEORA_QUALITY = 7
VORBIS_QUALITY = 4
## How many frames to pull back out of the encoded file for the palette audit.
AUDIT_SAMPLES = 8


# --------------------------------------------------------------------------- #
# encoder discovery
# --------------------------------------------------------------------------- #
def find_ffmpeg() -> str | None:
    """An ffmpeg that can encode Theora, or None. Never guesses a path."""
    candidates: list[str] = []
    env = os.environ.get("FFMPEG")
    if env:
        candidates.append(env)
    on_path = shutil.which("ffmpeg")
    if on_path:
        candidates.append(on_path)
    try:
        import imageio_ffmpeg  # type: ignore

        candidates.append(imageio_ffmpeg.get_ffmpeg_exe())
    except Exception:
        pass
    for candidate in candidates:
        if not candidate:
            continue
        try:
            out = subprocess.run(
                [candidate, "-hide_banner", "-encoders"],
                capture_output=True,
                text=True,
                timeout=120,
            )
        except (OSError, subprocess.SubprocessError):
            continue
        if "libtheora" in out.stdout:
            return candidate
    return None


# --------------------------------------------------------------------------- #
# encode + verify
# --------------------------------------------------------------------------- #
def encode(ffmpeg: str, source: Path, target: Path) -> None:
    """Re-encode the committed ident. Video and audio are mapped, not mixed."""
    command = [
        ffmpeg, "-y", "-hide_banner", "-loglevel", "error",
        "-i", str(source),
        "-map", "0:v:0",
        # `?` makes the audio stream optional: an ident without an audio bed
        # still encodes, and one with it is never silently muted.
        "-map", "0:a:0?",
        "-c:v", "libtheora", "-q:v", str(THEORA_QUALITY), "-pix_fmt", "yuv420p",
        "-c:a", "libvorbis", "-q:a", str(VORBIS_QUALITY),
        str(target),
    ]
    result = subprocess.run(command, capture_output=True, text=True, timeout=1800)
    if result.returncode != 0 or not target.exists():
        raise RuntimeError(f"ffmpeg failed on {target.name}:\n{result.stderr.strip()}")


def probe(ffmpeg: str, path: Path) -> dict:
    """Stream facts parsed out of ffmpeg's own header dump."""
    result = subprocess.run(
        [ffmpeg, "-hide_banner", "-i", str(path)],
        capture_output=True,
        text=True,
        timeout=300,
    )
    text = result.stderr
    info: dict = {}
    match = re.search(r"Duration: (\d+):(\d+):([\d.]+)", text)
    if match:
        hours, minutes, seconds = match.groups()
        info["duration_s"] = round(int(hours) * 3600 + int(minutes) * 60 + float(seconds), 3)
    # Codec-agnostic on purpose: the same probe reads the committed mp4
    # (h264) and the encode (theora), which is what lets the build compare
    # the two frame sizes instead of assuming the source's.
    match = re.search(r"Video: (\w+).*?, (\d+)x(\d+)", text)
    if match:
        info["codec"] = match.group(1)
        info["size"] = [int(match.group(2)), int(match.group(3))]
    match = re.search(r"(\d+(?:\.\d+)?) fps", text)
    if match:
        info["fps"] = float(match.group(1))
    info["has_audio"] = "Audio: vorbis" in text
    match = re.search(r"Video: theora.*? (\d+) kb/s", text)
    if match:
        info["video_kbps"] = int(match.group(1))
    info["bytes"] = path.stat().st_size
    return info


def audit_shipped_frames(ffmpeg: str, path: Path) -> dict:
    """Sample frames back out of the encoded file and run the palette audit.

    The frames come out of the file that ships, not out of a renderer, so a
    codec artefact that pushed a frame off-palette would be caught here.
    """
    with tempfile.TemporaryDirectory(prefix="aegis-audit-") as tmp:
        pattern = str(Path(tmp) / "%03d.png")
        subprocess.run(
            [ffmpeg, "-y", "-hide_banner", "-loglevel", "error", "-i", str(path),
             "-vf", "fps=1", "-frames:v", str(AUDIT_SAMPLES), pattern],
            capture_output=True, text=True, timeout=600,
        )
        frames = sorted(Path(tmp).glob("*.png"))
        if not frames:
            return {"sampled_frames": 0, "off_palette_share": 0.0, "within_palette": False}
        samples = [art.audit(frame) for frame in frames]
        return {
            "sampled_frames": len(samples),
            "off_palette_share": round(max(s["off_palette_share"] for s in samples), 4),
            "within_palette": all(s["within_palette"] for s in samples),
        }


def build(args: argparse.Namespace) -> int:
    ffmpeg = find_ffmpeg()
    if ffmpeg is None:
        print("ERROR: no ffmpeg with libtheora found. Set FFMPEG, put one on PATH,\n"
              "       or: pip3 install --break-system-packages imageio-ffmpeg")
        return 2
    print(f"encoder: {ffmpeg}")

    problems: list[str] = []
    manifest: dict = {
        "encoder": "libtheora",
        "container": "ogv",
        # What the file is allowed to be is as much a fact about it as its
        # duration, and it is the fact a future edit is most likely to get
        # wrong, so it is recorded next to the numbers.
        "note": ROLE,
        "videos": [],
    }
    target = OUT / IDENT_OUT

    if not SOURCE.exists():
        print(f"ERROR: the committed opening is missing at {SOURCE.relative_to(ROOT)}")
        return 1

    if args.check:
        if not target.exists():
            print(f"ERROR: {IDENT_OUT} is missing")
            return 1
        info = probe(ffmpeg, target)
        shipped = audit_shipped_frames(ffmpeg, target)
        print(f"ok  {IDENT_OUT:<24} {info.get('size')}  {info.get('duration_s')}s  "
              f"{info['bytes'] // 1024} kB  off-palette {shipped['off_palette_share'] * 100:.1f}%")
        manifest["videos"].append({"key": "studio_ident",
                                   "role": ROLE,
                                   "file": f"res://assets/ui/{IDENT_OUT}",
                                   **info, **shipped})
        print("\n--check: nothing written.")
    else:
        try:
            encode(ffmpeg, SOURCE, target)
        except RuntimeError as error:
            problems.append(str(error))
        if target.exists():
            info = probe(ffmpeg, target)
            shipped = audit_shipped_frames(ffmpeg, target)
            source_info = probe(ffmpeg, SOURCE)
            entry = {
                "key": "studio_ident",
                "role": ROLE,
                "file": f"res://assets/ui/{IDENT_OUT}",
                "format": "OGV (Theora + Vorbis)",
                "source": str(SOURCE.relative_to(ROOT)),
                "source_size": source_info.get("size"),
                "source_duration_s": source_info.get("duration_s"),
                "size": info.get("size"),
                "fps": IDENT_FPS,
                "duration_s": info.get("duration_s"),
                "bytes": info["bytes"],
                "has_audio": info.get("has_audio", False),
                **shipped,
            }
            manifest["videos"].append(entry)
            flag = "ok " if shipped["within_palette"] else "note"
            print(f"{flag} {IDENT_OUT:<24} {entry['size'][0]}x{entry['size'][1]}  "
                  f"{entry['duration_s']}s @ {IDENT_FPS} fps  "
                  f"{info['bytes'] // 1024} kB  audio {entry['has_audio']}  "
                  f"off-palette {shipped['off_palette_share'] * 100:.1f}%")
            if not shipped["within_palette"]:
                print("     ^ off-palette is expected: the ident's lime sits between "
                      "the amber and green windows (see palette_exemption).")
                # Exempt, and measured rather than forgiven. The ident's
                # signature colour is lime: hue 75-90, which falls in the gap
                # between the ART_DIRECTION amber window (15-70) and its green
                # window (95-175). That colour is the studio's, the film is the
                # project owner's committed asset, and no rule here may re-grade
                # it. It is recorded so the number is visible if the source is
                # ever swapped for something that really did drift.
                entry["palette_exemption"] = (
                    "the committed brand ident (lime, hue 75-90) is outside the "
                    "game-art palette by design; supplied, not generated"
                )
            # The encode must carry the film it was given: a silent or
            # truncated output is the failure a "file exists" check misses.
            if not entry["has_audio"] and source_info.get("has_audio", True):
                problems.append("studio_ident: the source has audio and the encode does not")
            if (info.get("size") != source_info.get("size")):
                problems.append(
                    "studio_ident: frame size changed "
                    f"{source_info.get('size')} -> {info.get('size')}"
                )
        MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        print(f"\nmanifest: {MANIFEST.relative_to(ROOT)}")

    for problem in problems:
        print(f"ERROR: {problem}")
    return 1 if problems else 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true", help="verify only, write nothing")
    return build(parser.parse_args())


if __name__ == "__main__":
    sys.exit(main())
